const normalize = (value = '') => String(value || '').trim().toLowerCase();
const CITY_ALIASES = {
  varansi: 'Varanasi',
  banaras: 'Varanasi',
  benaras: 'Varanasi',
};

export function getStateForCity(city) {
  const canonical = CITY_ALIASES[normalize(city)] || city;
  const match = Object.keys(CITY_TO_STATE).find(name => normalize(name) === normalize(canonical));
  return match ? CITY_TO_STATE[match] : null;
}

export function getLocationImages(cityOrState) {
  const canonical = CITY_ALIASES[normalize(cityOrState)] || cityOrState;
  const city = Object.keys(LOCATION_IMAGES).find(name => normalize(name) === normalize(canonical));
  if (city) return LOCATION_IMAGES[city];

  const state = Object.keys(STATE_IMAGES).find(name => normalize(name) === normalize(canonical));
  if (state) return STATE_IMAGES[state];

  const inferredState = getStateForCity(canonical);
  return inferredState ? STATE_IMAGES[inferredState] : DEFAULT_LOCATION_IMAGES;
}

export function nearestKnownCity(coords) {
  if (!coords?.lat || !coords?.lng) return null;
  const toRad = value => (value * Math.PI) / 180;
  const distance = ([lat, lng]) => {
    const dLat = toRad(lat - coords.lat);
    const dLng = toRad(lng - coords.lng);
    const a = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(coords.lat)) * Math.cos(toRad(lat)) * Math.sin(dLng / 2) ** 2;
    return 6371 * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  };

  return Object.entries(CITY_COORDS)
    .map(([city, cityCoords]) => ({ city, distance: distance(cityCoords) }))
    .sort((a, b) => a.distance - b.distance)[0]?.city || null;
}
